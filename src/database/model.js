import { postgresColumnType } from './native-text-sql.js';
import model from './native-model.json' with { type: 'json' };

export const nativeModel = model;
export const postgresStorageModel = Object.freeze({ ...model, tables: model.tables.map(table => ({ ...table, columns: table.columns.map(column => ({ ...column, pgType: postgresColumnType(column) })) })) });
export const quoteIdentifier = (value) => `"${String(value).replaceAll('"', '""')}"`;
export function tableDefinition(name) {
  const table = model.tables.find((entry) => entry.name === name);
  if (!table) throw new Error(`Unknown native table: ${name}`);
  return table;
}
export function columnDefinition(table, name) {
  const column = table.columns.find((entry) => entry.name === name);
  if (!column) throw new Error(`Unknown native column: ${table.name}.${name}`);
  return column;
}

export function createTableSql(table, dialect = 'sqlite') {
  const q = quoteIdentifier;
  const columns = table.columns.map((column) => {
    let sql = `${q(column.name)} ${dialect === 'sqlite' ? column.type : postgresColumnType(column)}`;
    if (dialect === 'postgres' && column.generated) sql += ' GENERATED BY DEFAULT AS IDENTITY';
    if (!column.nullable) sql += ' NOT NULL';
    if (column.default !== undefined) {
      let value = column.default;
      if (dialect === 'postgres' && column.type === 'TEXT') {
        if (!/^'(?:[^']|'')*'$/.test(value)) throw new TypeError('Native TEXT defaults require literal bytes.');
        const bytes = Buffer.from(value.slice(1, -1).replaceAll("''", "'"), 'utf8');
        value = `decode('${bytes.toString('hex')}', 'hex')`;
      } else if (dialect === 'postgres' && column.pgType === 'boolean') value = value === '0' ? 'false' : 'true';
      sql += ` DEFAULT ${value}`;
    }
    if (dialect === 'sqlite' && column.generated) sql += ' PRIMARY KEY AUTOINCREMENT';
    if (dialect === 'postgres' && column.clrType.replace('?', '') === 'uint') sql += ` CHECK (${q(column.name)} BETWEEN 0 AND 4294967295)`;
    return sql;
  });
  if (!(dialect === 'sqlite' && table.columns.some((column) => column.generated))) columns.push(`CONSTRAINT ${q(`PK_${table.name}`)} PRIMARY KEY (${table.primaryKey.map(q).join(', ')})`);
  for (const fk of table.foreignKeys) columns.push(`CONSTRAINT ${q(`FK_${table.name}_${fk.table}_${fk.columns.join('_')}`)} FOREIGN KEY (${fk.columns.map(q).join(', ')}) REFERENCES ${q(fk.table)} (${fk.referencedColumns.map(q).join(', ')}) ON DELETE ${fk.onDelete}${dialect === 'postgres' ? ' DEFERRABLE INITIALLY IMMEDIATE' : ''}`);
  return `CREATE TABLE ${q(table.name)} (\n  ${columns.join(',\n  ')}\n)`;
}

export function createIndexSql(table, index, dialect = 'sqlite', { schema } = {}) {
  // SQLite's built-in lower() folds ASCII only. A locale-aware PostgreSQL lower()
  // would produce a different equivalence class for imported person names.
  const expression = index.expression && dialect === 'postgres' ? `${schema ? quoteIdentifier(schema) + '.' : ''}mm_native_ascii_lower("Name")` : index.expression;
  return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${quoteIdentifier(index.name)} ON ${quoteIdentifier(table.name)} (${expression ?? index.columns.map(quoteIdentifier).join(', ')})${index.filter ? ` WHERE ${index.filter}` : ''}`;
}

export function dependencyOrder(tables = model.tables) {
  const result = [];
  const remaining = [...tables];
  while (remaining.length) {
    const index = remaining.findIndex((table) => table.foreignKeys.every((fk) => fk.table === table.name || result.some((added) => added.name === fk.table)));
    if (index < 0) throw new Error('Cross-table foreign key cycle is not supported');
    result.push(remaining.splice(index, 1)[0]);
  }
  return result;
}
