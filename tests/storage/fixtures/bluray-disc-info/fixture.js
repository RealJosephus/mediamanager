// Build standard MPLS/CLPI records as controlled inputs, not expected outputs.
export function makeClipInfo({ streams, version = '0200' }) {
  const entries = streams.map(stream => {
    let descriptor;
    if ([1, 2, 0x1b, 0x20, 0x24, 0xea].includes(stream.type)) {
      descriptor = Buffer.from([stream.type, (stream.format << 4) | stream.rate, 0x30]);
    } else if ([0x90, 0x91].includes(stream.type)) {
      descriptor = Buffer.concat([Buffer.from([stream.type]), Buffer.from(stream.language, 'ascii')]);
    } else if (stream.type === 0x92) {
      descriptor = Buffer.concat([Buffer.from([stream.type, 1]), Buffer.from(stream.language, 'ascii')]);
    } else {
      descriptor = Buffer.concat([Buffer.from([stream.type, (stream.layout << 4) | stream.rate]), Buffer.from(stream.language, 'ascii')]);
    }
    const entry = Buffer.alloc(3 + descriptor.length);
    entry.writeUInt16BE(stream.pid); entry[2] = descriptor.length; descriptor.copy(entry, 3); return entry;
  });
  const program = Buffer.alloc(10); program[1] = 1; program[8] = streams.length;
  const body = Buffer.concat([program, ...entries]);
  const result = Buffer.alloc(0x44 + body.length);
  result.write('HDMV' + version); result.writeUInt32BE(0x40, 12); result.writeUInt32BE(body.length, 0x40); body.copy(result, 0x44);
  return result;
}

export function makePlaylist({ items, marks = [], version = '0200' }) {
  const entries = items.map(item => {
    const angles = item.angles ?? [];
    // Hidden-track diagnostics do not remove CLPI tracks from examiner output.
    const body = Buffer.alloc(32 + (angles.length ? 2 + angles.length * 10 : 0) + 16);
    body.write(item.clip); body.write('M2TS', 5); body[10] = angles.length ? 0x10 : 0;
    body.writeUInt32BE(item.in, 12); body.writeUInt32BE(item.out, 16);
    let offset = 32;
    if (angles.length) {
      body[offset] = angles.length + 1; offset += 2;
      for (const name of angles) { body.write(name, offset); body.write('M2TS', offset + 5); offset += 10; }
    }
    body.writeUInt16BE(14, offset);
    const result = Buffer.alloc(2 + body.length); result.writeUInt16BE(body.length); body.copy(result, 2); return result;
  });
  const playlist = Buffer.alloc(6); playlist.writeUInt16BE(items.length, 2);
  const body = Buffer.concat([playlist, ...entries]);
  const markData = Buffer.alloc(2 + marks.length * 14); markData.writeUInt16BE(marks.length);
  for (const [index, mark] of marks.entries()) {
    const offset = 2 + index * 14;
    markData[offset + 1] = mark.type ?? 1; markData.writeUInt16BE(mark.item, offset + 2); markData.writeUInt32BE(mark.time, offset + 4);
  }
  const markOffset = 0x44 + body.length, result = Buffer.alloc(markOffset + 4 + markData.length);
  result.write('MPLS' + version); result.writeUInt32BE(0x40, 8); result.writeUInt32BE(markOffset, 12);
  result.writeUInt32BE(body.length, 0x40); body.copy(result, 0x44);
  result.writeUInt32BE(markData.length, markOffset); markData.copy(result, markOffset + 4); return result;
}

export function makeBlurayFiles(input, media = Buffer.alloc(192)) {
  return new Map([
    ...input.clips.flatMap(clip => [[`BDMV/CLIPINF/${clip.id}.clpi`, makeClipInfo(clip)], [`BDMV/STREAM/${clip.id}.m2ts`, media]]),
    ...input.playlists.map(playlist => [`BDMV/PLAYLIST/${playlist.id}.mpls`, makePlaylist(playlist)])
  ]);
}

// Controlled transport declaration only: retain the generated H.264 PES bytes
// and change the second video's PMT type to MVC. This does not create or claim
// a stereoscopic elementary stream. Accept only the small single-packet PMTs
// generated by this fixture; a different mux layout must fail visibly.
export function declareMvcInM2ts(source, pid = 4114) {
  if (!source.length || source.length % 192 !== 0) throw new Error('Expected complete 192-byte M2TS packets.');
  const bytes = Buffer.from(source), changes = [];
  const crc32 = body => {
    let crc = 0xffffffff;
    for (const value of body) {
      crc ^= value << 24;
      for (let bit = 0; bit < 8; bit++) crc = ((crc << 1) ^ (crc & 0x80000000 ? 0x04c11db7 : 0)) >>> 0;
    }
    return crc >>> 0;
  };
  for (let packet = 0; packet < bytes.length; packet += 192) {
    const sync = packet + 4, end = packet + 192;
    if (bytes[sync] !== 0x47) throw new Error('The generated transport lost packet alignment.');
    const control = (bytes[sync + 3] >> 4) & 3;
    if (!(control & 1) || !(bytes[sync + 1] & 0x40)) continue;
    const payload = sync + 4 + (control & 2 ? 1 + bytes[sync + 4] : 0);
    if (payload >= end) throw new Error('The generated transport has no section payload.');
    const section = payload + 1 + bytes[payload];
    if (section >= end || bytes[section] !== 2) continue;
    if (section + 12 > end) throw new Error('The generated PMT header spans packets.');
    const sectionEnd = section + 3 + (bytes.readUInt16BE(section + 1) & 0xfff), crcOffset = sectionEnd - 4;
    if (sectionEnd > end || crcOffset < section + 12) throw new Error('The generated PMT is not a bounded single-packet section.');
    if (crc32(bytes.subarray(section, sectionEnd)) !== 0) throw new Error('The generated PMT CRC is invalid.');
    let offset = section + 12 + (bytes.readUInt16BE(section + 10) & 0xfff), typeOffset;
    while (offset < crcOffset) {
      if (offset + 5 > crcOffset) throw new Error('The generated PMT stream record is truncated.');
      const next = offset + 5 + (bytes.readUInt16BE(offset + 3) & 0xfff);
      if (next > crcOffset) throw new Error('The generated PMT descriptor is truncated.');
      if ((bytes.readUInt16BE(offset + 1) & 0x1fff) === pid) {
        if (typeOffset !== undefined || bytes[offset] !== 0x1b) throw new Error('Expected one AVC declaration for the controlled MVC PID.');
        typeOffset = offset;
      }
      offset = next;
    }
    if (offset !== crcOffset || typeOffset === undefined) throw new Error('The generated PMT does not contain the controlled video PID.');
    const beforeCrc = bytes.readUInt32BE(crcOffset);
    bytes[typeOffset] = 0x20;
    const afterCrc = crc32(bytes.subarray(section, crcOffset)); bytes.writeUInt32BE(afterCrc, crcOffset);
    changes.push({ packet, pmtPid: bytes.readUInt16BE(sync + 1) & 0x1fff, pid, typeOffset,
      beforeType: 0x1b, afterType: 0x20, crcOffset, beforeCrc, afterCrc });
  }
  if (!changes.length) throw new Error('No generated PMT declaration was changed.');
  return { bytes, changes };
}
