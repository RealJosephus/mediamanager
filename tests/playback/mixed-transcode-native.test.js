async function seedDovi(hdrFilename, frameRate, evidence, signal) {
  const directory = path.dirname(hdrFilename);
  const video = await runMediaTool('ffmpeg', ['-v', 'error', '-i', hdrFilename, '-map', '0:v:0', '-frames:v', '24',
    '-c:v', 'libx265', '-pix_fmt', 'yuv420p10le', '-preset', 'ultrafast',
    '-color_trc', 'smpte2084', '-color_primaries', 'bt2020', '-colorspace', 'bt2020nc',
    '-x265-params', 'pools=1:frame-threads=1:log-level=error:bframes=0:aud=1:hdr10=1:repeat-headers=1', '-f', 'hevc', '-'],
  evidence.commands, signal);
  const accessUnitDelimiter = Buffer.from([0, 0, 1, 0x46, 1]);
  const parts = [];
  let start = 0, units = 0;
  for (let offset = video.indexOf(accessUnitDelimiter); offset !== -1; offset = video.indexOf(accessUnitDelimiter, offset + accessUnitDelimiter.length)) {
    const boundary = offset > 0 && video[offset - 1] === 0 ? offset - 1 : offset;
    if (units++) {
      parts.push(video.subarray(start, boundary), rpuNal);
      start = boundary;
    }
  }
  assert.equal(units, 24);
  parts.push(video.subarray(start), rpuNal);
  const elementary = path.join(directory, 'dovi.hevc');
  await writeFile(elementary, Buffer.concat(parts), { signal });
  const videoOnly = path.join(directory, 'dovi-video.mp4');
  await runMediaTool('ffmpeg', ['-v', 'error', '-fflags', '+genpts', '-framerate', frameRate, '-f', 'hevc', '-i', elementary,
    '-map', '0:v:0', '-c:v', 'copy', '-bsf:v', 'dovi_rpu=compression=none', '-tag:v:0', 'dvh1', '-strict', '-2', videoOnly],
  evidence.commands, signal);
  const filename = path.join(directory, 'dovi.mp4');
  await runMediaTool('ffmpeg', ['-v', 'error', '-i', videoOnly,
    '-f', 'lavfi', '-i', 'sine=frequency=997:sample_rate=48000:duration=0.64',
    '-map', '0:v:0', '-map', '1:a:0', '-c:v', 'copy', '-c:a', 'ac3', '-ac', '2', '-b:a', '192000',
    '-tag:v:0', 'dvh1', '-strict', '-2', filename], evidence.commands, signal);
  const bytes = await readFile(filename);
  const configurationBox = Math.max(bytes.indexOf('dvcC'), bytes.indexOf('dvvC'));
  assert.ok(configurationBox >= 4 && bytes.readUInt32BE(configurationBox - 4) >= 13);
  const compatibilityOffset = configurationBox + 8;
  assert.equal(bytes[compatibilityOffset] >> 4, 1);
  const invalidBytes = Buffer.from(bytes);
  invalidBytes[compatibilityOffset] &= 0x0f;
  const invalid = path.join(directory, 'invalid-dovi.mp4');
  await writeFile(invalid, invalidBytes, { signal });
  const sources = [];
  for (const [id, name, file, data, compatibility] of [
    [doviItemId, 'Dolby Vision fixture', filename, bytes, 1],
    [invalidDoviItemId, 'Invalid Dolby Vision configuration fixture', invalid, invalidBytes, 0],
  ]) {
    const raw = await probe(file, evidence, signal);
    const media = normalizeProbe(raw, { path: file, protocol: 'File' });
    const stream = media.MediaStreams.find(value => value.Type === 'Video');
    assert.deepEqual([stream.Codec, stream.ColorTransfer, stream.DvProfile, stream.DvBlSignalCompatibilityId], ['hevc', 'smpte2084', 8, compatibility]);
    const audio = media.MediaStreams.find(value => value.Type === 'Audio');
    assert.deepEqual([audio?.Index, audio?.Codec, audio?.Channels], [1, 'ac3', 2]);
    sources.push({ id, name, filename: file, bytes: data, media });
  }
  return sources;
}

